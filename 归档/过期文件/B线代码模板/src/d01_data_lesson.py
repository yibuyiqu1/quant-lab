# -*- coding: utf-8 -*-
"""Day 1 教学版 · 数据获取（每一行都有注释，零基础可读）

这个文件只做一件事：
    把沪深300 指数日线数据从网上抓下来，存成本地两个文件，
    以后所有分析都读本地，不再联网。

运行前确认你用的是项目虚拟环境：
    cd /d "E:\AI结果\量化"
    .venv\Scripts\python.exe src\d01_data_lesson.py

预期输出：data/raw/hs300.csv（Excel 能打开）和 data/clean/hs300.parquet（分析用）
"""
# =============================================================================
# 【第 0 部分】导入需要用到的包
# -----------------------------------------------------------------------------
# 语法说明：import X          导入整个包，之后用 X.函数() 调用
#           from X import Y   只导入包里的 Y，之后直接写 Y()
# 下面每个包的作用见文件末尾的《包速查表》
# =============================================================================
import os                      # os：操作系统接口。这里只用来拼路径、建文件夹
import sys                     # sys：解释器相关设置。这里只用来把输出改成 UTF-8

import akshare as ak           # akshare：免费开源的中国金融数据接口库（不需要注册）
import pandas as pd            # pandas：表格数据处理（DataFrame / Series）

# 让 print 出来的中文在 PowerShell 里不乱码（Windows 默认是 GBK 编码）
sys.stdout.reconfigure(encoding="utf-8")


# =============================================================================
# 【第 1 部分】路径设置：算出项目根目录，再拼接数据文件路径
# -----------------------------------------------------------------------------
# 写法解释：
#   __file__            当前这个 py 文件的路径（字符串）
#   os.path.abspath()   转成绝对路径，消除 ".." 这类相对写法
#   os.path.dirname()   取上一级目录
# 两层 dirname：文件在 项目/src/xx.py  →  第一层得到 项目/src  →  第二层得到 项目
# 为什么不写死 "E:\AI结果\量化"？因为写死了换电脑/换目录就报错。
# =============================================================================
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

RAW_PATH = os.path.join(ROOT, "data", "raw", "hs300.csv")        # 原始数据（给人看）
CLEAN_PATH = os.path.join(ROOT, "data", "clean", "hs300.parquet")  # 清洗后（给程序用）

# 打印出来确认路径对不对——这是排查路径问题的第一手段
print("项目根目录 :", ROOT)
print("原始数据将存到:", RAW_PATH)
print("清洗数据将存到:", CLEAN_PATH)


# =============================================================================
# 【第 2 部分】把主逻辑写进 main() 函数
# -----------------------------------------------------------------------------
# 为什么要有 main()？
#   1) 变量都在函数内部，不会污染全局
#   2) 文件可以被别的脚本 import 而不执行抓取
#   3) 配合末尾的 if __name__ == "__main__" 使用
# =============================================================================
def main() -> None:
    # -------------------------------------------------------------------------
    # 2.1 建好目录
    # os.makedirs(路径, exist_ok=True)
    #   - 会一次性创建缺失的多层目录（data 和 data/raw 都自动建）
    #   - exist_ok=True 表示"目录已存在就不要报错"
    #   - 必须写这行！否则后面存文件会 FileNotFoundError
    # -------------------------------------------------------------------------
    os.makedirs(os.path.dirname(RAW_PATH), exist_ok=True)
    os.makedirs(os.path.dirname(CLEAN_PATH), exist_ok=True)

    # -------------------------------------------------------------------------
    # 2.2 抓数据
    # ak.stock_zh_index_daily(symbol="sh000300")
    #   - 返回值直接就是 pandas 的 DataFrame（表格）
    #   - symbol 规则：前缀 sh=上交所 / sz=深交所 + 6 位代码
    #       上证指数 sh000001   沪深300 sh000300   中证500 sh000905   创业板指 sz399006
    #   - 列固定为：date / open / high / low / close / volume
    #     注意：这个接口的 date 是"文本"类型，不是日期类型，下一步必须转
    #   - 需要联网；如果公司/学校网络拦截，会抛异常，见文件末尾《报错对照》
    # -------------------------------------------------------------------------
    print("\n正在从网络抓取沪深300日线 ...")
    df = ak.stock_zh_index_daily(symbol="sh000300")

    # 打印形状(行数, 列数)和列名——拿到任何新数据的第一步都是先看它长什么样
    print("抓取成功，形状(行数, 列数) =", df.shape)
    print("列名 =", list(df.columns))

    # -------------------------------------------------------------------------
    # 2.3 把 date 列从文本转成真正的时间类型
    #     pd.to_datetime(某列) 会把 "2002-01-04" 这种字符串变成 Timestamp
    #     为什么必须转？
    #       - 不转的话，df["date"] > "2024-01-01" 只是字符串比较，结果不可靠
    #       - 也没法用 .dt 访问器（取年、月、星期）和 .resample() 按月汇总
    #   df["date"] = ... 是"给这一列重新赋值"，即替换原来的列
    # -------------------------------------------------------------------------
    df["date"] = pd.to_datetime(df["date"])

    # -------------------------------------------------------------------------
    # 2.4 排序 + 重置索引
    #     sort_values("date")    按日期从小到大排（原始顺序通常已升序，但别假设）
    #     reset_index(drop=True) 重排行号 0,1,2,...；
    #                            不加 drop=True 会把旧行号变成新的一列
    #     df = df.xxx  表示把处理结果赋回给 df 这个名字（链式操作的常见写法）
    # -------------------------------------------------------------------------
    df = df.sort_values("date").reset_index(drop=True)

    # -------------------------------------------------------------------------
    # 2.5 简单体检：日期区间、缺失值、重复日期
    #     df["date"].min() / .max()  取最早 / 最晚日期
    #     f"{变量:%Y-%m-%d}"         把日期格式化成 年-月-日 输出
    #     df.isna().sum()            对每列统计缺失值个数
    #     df["date"].duplicated().sum()  统计重复的日期有几个
    #     这三项是"数据可用性"的最低要求，任何时候拿到新数据都要先查
    # -------------------------------------------------------------------------
    print(f"\n日期区间: {df['date'].min():%Y-%m-%d} ~ {df['date'].max():%Y-%m-%d}")
    print("每列缺失值个数:\n" + df.isna().sum().to_string())
    print("重复日期个数:", int(df["date"].duplicated().sum()))

    # -------------------------------------------------------------------------
    # 2.6 存成 CSV —— 给人看的版本
    #     to_csv(路径, index=False, encoding="utf-8-sig")
    #       index=False        不要把 pandas 的行号写进文件（否则多一列无名列）
    #       encoding="utf-8-sig"  带 BOM 的 UTF-8；用 Excel 直接打开中文不乱码
    #     缺点：体积大、读写慢、日期类型会退化成文本
    # -------------------------------------------------------------------------
    df.to_csv(RAW_PATH, index=False, encoding="utf-8-sig")
    print(f"\n已保存 CSV  : {RAW_PATH}")

    # -------------------------------------------------------------------------
    # 2.7 存成 parquet —— 给程序用的版本
    #     to_parquet(路径, index=False)
    #       优点：体积约为 CSV 的 1/3；读写快 5-10 倍；保留列的数据类型（日期还是日期）
    #       前提：装了 pyarrow 或 fastparquet（我们装了 pyarrow）
    #     以后所有分析脚本都读这个文件，速度和对类型的处理都更好
    # -------------------------------------------------------------------------
    df.to_parquet(CLEAN_PATH, index=False)
    print(f"已保存 parquet: {CLEAN_PATH}")

    # -------------------------------------------------------------------------
    # 2.8 打印最后 3 行，肉眼确认"最新数据确实是最近的交易日"
    #     df.tail(3)            取最后 3 行
    #     .to_string(index=False) 打印成表格且不显示行号（更好看）
    # -------------------------------------------------------------------------
    print("\n最后 3 行数据（确认最新日期）:")
    print(df.tail(3).to_string(index=False))

    # 收尾提醒：下一步该干什么
    print("\n下一步: 运行 src\\d01_analysis_lesson.py 做统计分析")


# =============================================================================
# 【第 3 部分】入口判断
# -----------------------------------------------------------------------------
# __name__ 在"直接运行本文件"时等于 "__main__"；
# 被别的文件 import 时等于模块名（"d01_data_lesson"）。
# 所以这行的意思是：只有直接运行本文件才执行 main()，
# 被别人 import 时不会偷偷抓数据（这是 Python 的标准工程写法）。
# =============================================================================
if __name__ == "__main__":
    main()
